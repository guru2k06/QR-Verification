const { PDFDocument, rgb, StandardFonts } = require('pdf-lib');

/**
 * Auto-generates a clean A4 PDF document containing the provided metadata.
 * @param {Object} metadata 
 * @returns {Promise<Buffer>}
 */
async function generateDefaultPdf(metadata) {
  try {
    const pdfDoc = await PDFDocument.create();
    const page = pdfDoc.addPage([600, 800]); // Portrait

    const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
    const fontRegular = await pdfDoc.embedFont(StandardFonts.Helvetica);

    // Title / Document Type
    page.drawText(metadata.documentType || 'Secure Document', {
      x: 50,
      y: 730,
      size: 24,
      font: fontBold,
      color: rgb(0.1, 0.2, 0.3)
    });

    // Horizontal Rule
    page.drawLine({
      start: { x: 50, y: 710 },
      end: { x: 550, y: 710 },
      thickness: 1,
      color: rgb(0.8, 0.8, 0.8)
    });

    let y = 670;
    const drawLine = (label, value) => {
      if (value == null || value === '') return;
      page.drawText(`${label}:`, { x: 50, y, size: 12, font: fontBold, color: rgb(0.2, 0.2, 0.2) });
      page.drawText(`${value}`, { x: 200, y, size: 12, font: fontRegular, color: rgb(0.1, 0.1, 0.1) });
      y -= 30;
    };

    drawLine('Recipient', metadata.recipientName);
    drawLine('Issuer', metadata.issuer);

    const issueDateStr = metadata.issueDate instanceof Date 
      ? metadata.issueDate.toISOString().slice(0, 10) 
      : String(metadata.issueDate || '');
    drawLine('Issue Date', issueDateStr);

    y -= 10; // Extra spacing before specific fields

    if (metadata.typeSpecificData) {
      Object.keys(metadata.typeSpecificData).forEach(key => {
        // Format camelCase to Title Case (e.g. "studentName" -> "Student Name")
        const label = key.replace(/([A-Z])/g, ' $1').replace(/^./, str => str.toUpperCase());
        drawLine(label, metadata.typeSpecificData[key]);
      });
    }

    // Footer note
    page.drawText('This document was automatically generated by the secure ledger.', {
      x: 50,
      y: 100,
      size: 10,
      font: fontRegular,
      color: rgb(0.5, 0.5, 0.5)
    });

    const pdfBytes = await pdfDoc.save();
    return Buffer.from(pdfBytes);
  } catch (error) {
    console.error('Failed to generate default PDF:', error);
    throw error;
  }
}

module.exports = generateDefaultPdf;
